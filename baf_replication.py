import numpy as np
import pandas as pd
import tensorflow as tf
from lightgbm import LGBMClassifier
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.metrics import classification_report, precision_recall_curve, auc
import matplotlib.pyplot as plt
import warnings
warnings.filterwarnings('ignore')

print("Libraries imported successfully.")

X = df.drop(columns=['fraud_bool'])
y = df['fraud_bool']

# 3. Identify Column Types
numeric_features = X.select_dtypes(include=['int64', 'float64']).columns.tolist()
categorical_features = X.select_dtypes(include=['object', 'category']).columns.tolist()

# 4. Build the Pipeline (Matching the Paper exactly)
numeric_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(missing_values=-1, strategy='median')),
    ('scaler', StandardScaler())
])

categorical_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='constant', fill_value='__missing__')),
    ('onehot', OneHotEncoder(handle_unknown='ignore'))
])

preprocessor = ColumnTransformer(transformers=[
    ('num', numeric_transformer, numeric_features),
    ('cat', categorical_transformer, categorical_features)
])

# 5. Split and Process Data
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)

X_train_processed = preprocessor.fit_transform(X_train)
X_test_processed = preprocessor.transform(X_test)

# 6. Calculate Static Penalty
fraud_ratio = y_train.value_counts()[0] / y_train.value_counts()[1]
print(f"Calculated Static Class Weight (Penalty): {fraud_ratio:.2f}")

"""## 🌳 Baseline 1: LightGBM (Classical Tree-Based)
Training the standard gradient boosting model with the static class weight applied to the objective.
"""

# Initialize and Train LightGBM
lgbm = LGBMClassifier(
    scale_pos_weight=fraud_ratio, # The critical 89.67 penalty
    random_state=42,
    n_jobs=-1
)

print("Training LightGBM...")
lgbm.fit(X_train_processed, y_train)

# Evaluate PR-AUC
y_probs_lgbm = lgbm.predict_proba(X_test_processed)[:, 1]
precision, recall, _ = precision_recall_curve(y_test, y_probs_lgbm)
pr_auc_lgbm = auc(recall, precision)

y_pred_lgbm = lgbm.predict(X_test_processed)

print(f"\n--- LIGHTGBM REPLICATION RESULTS ---")
print(f"PR-AUC Score: {pr_auc_lgbm:.4f}")
print("Classification Report:")
print(classification_report(y_test, y_pred_lgbm))

"""## 🧠 Baseline 2: Gated Recurrent Unit (Deep Learning)
Reshaping the 2D tabular array into a 3D sequential format and training the GRU to establish the high-recall performance ceiling.
"""

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import GRU, Dense, Dropout

# 1. Reshape data for GRU (Samples, Timesteps, Features)
# We treat the entire row of features as a single timestep containing all column data
X_train_gru = np.expand_dims(X_train_processed, axis=1)
X_test_gru = np.expand_dims(X_test_processed, axis=1)

# 2. Build GRU Architecture
model = Sequential([
    GRU(64, input_shape=(X_train_gru.shape[1], X_train_gru.shape[2]), return_sequences=True),
    Dropout(0.2),
    GRU(32),
    Dense(16, activation='relu'),
    Dense(1, activation='sigmoid')
])

model.compile(optimizer='adam', loss='binary_crossentropy')

# 3. Train with the Static Weight Class dictionary
class_weight_dict = {0: 1.0, 1: fraud_ratio}

print("Training GRU Model (This may take a few minutes)...")
history = model.fit(
    X_train_gru, y_train,
    epochs=5,
    batch_size=2048,
    class_weight=class_weight_dict,
    validation_split=0.1,
    verbose=1
)

# 4. Evaluate PR-AUC
y_probs_gru = model.predict(X_test_gru).ravel()
precision_g, recall_g, _ = precision_recall_curve(y_test, y_probs_gru)
pr_auc_gru = auc(recall_g, precision_g)

# Convert probabilities to binary predictions (Threshold 0.5)
y_pred_gru = (y_probs_gru > 0.5).astype(int)

print(f"\n--- GRU REPLICATION RESULTS ---")
print(f"PR-AUC Score: {pr_auc_gru:.4f}")
print("Classification Report:")
print(classification_report(y_test, y_pred_gru))

